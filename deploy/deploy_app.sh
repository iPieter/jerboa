#!/usr/bin/env bash
# Phase 2: deploy the backend at a git ref. About 10-30 s of API downtime.
#
#   ./deploy_app.sh <git-ref>        build chat:<sha> from that ref and switch to it
#   ./deploy_app.sh --rollback       stop the current container, start the previous one
#   ./deploy_app.sh --status         show what runs, then run the health check
#   options:
#     --rotate-flask-secret          replace flask_secret in an existing /root/jerboa.env
#     --force                        redeploy even if this commit is already running
#     --yes                          do not ask questions
#
# <git-ref> is a branch (security-fixes), a tag or a commit sha.
#
# Steps
#   1. Fetch https://github.com/iPieter/jerboa at <git-ref> into /root/jerboa-src
#      and show what differs from the code in the running container.
#   2. Build chat:<sha> = chat:latest (the 2020 image: Python 3.6 and every
#      dependency) + app/ (+ run.py if it changed). Nothing is installed or
#      upgraded, so the dependency set stays exactly as it is today.
#   3. Secrets live in /root/jerboa.env (0600). On the first run db_pass is copied
#      from the old image's .env without being printed, and flask_secret is NEW.
#      (The new image deletes that baked-in .env: the image's pipenv would
#      otherwise load it with override=True and silently beat --env-file.)
#      A new flask_secret invalidates every token: all users sign in again (the
#      iOS app re-logs in by itself). Later runs reuse the file.
#   4. Smoke test: import the new code in a throwaway container against the live
#      database. Import errors or a bad env file stop the deploy here, before
#      anything is touched.
#   5. Stop the old container (kept for rollback), start jerboa-app-<sha> with the
#      same mounts, --network host, --env-file, --restart unless-stopped and
#      json-file log caps (10m x 3).
#   6. Health check (/status, a DB-backed 404, socket.io handshake, nginx). On
#      failure the new container is stopped and the old one started again.

PHASE=deploy_app
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

REF=""
MODE=deploy
FORCE=0
ROTATE=0
for arg in "$@"; do
  case $arg in
    --rollback) MODE=rollback ;;
    --status) MODE=status ;;
    --force) FORCE=1 ;;
    --rotate-flask-secret) ROTATE=1 ;;
    --yes|-y) ASSUME_YES=1 ;;
    -h|--help) usage_and_exit ;;
    -*) die "unknown option: $arg (see --help)" ;;
    *) [[ -z $REF ]] || die "only one git ref, please"; REF=$arg ;;
  esac
done

# ------------------------------------------------------------- helpers ----

# The Dockerfile for the code-only image. Kept as a function so the tests can
# render it without docker.
render_dockerfile() { # <sha> <base-image-id> <copy-run.py 0|1>
  cat <<EOF
# Generated by deploy/deploy_app.sh for commit $1.
# A code-only layer on top of the original image: same Ubuntu 18.04, same
# Python 3.6, same pipenv virtualenv. Nothing is installed or upgraded here.
FROM $BASE_IMAGE

# Secrets come only from --env-file /root/jerboa.env. The 2020 image has a
# /chat_app/.env baked in, and its pipenv (2018.11.26) loads that file with
# override=True, which would silently replace the --env-file values (the new
# flask_secret would never take effect). So: delete it, and tell pipenv not to
# load any .env at all.
ENV PIPENV_DONT_LOAD_ENV=1
RUN rm -rf /chat_app/app /chat_app/.env

# Replace app/ as a whole, so files deleted upstream really disappear.
COPY app/ /chat_app/app/
EOF
  if [[ $3 == 1 ]]; then
    echo 'COPY run.py /chat_app/run.py'
  fi
  cat <<EOF

LABEL org.opencontainers.image.source="$REPO_URL" \\
      org.opencontainers.image.revision="$1" \\
      jerboa.base-image="$2"
EOF
}

# Write a fresh env file. Values go through printf (a builtin), never argv.
write_env_file() { # <path> <db_pass> <flask_secret>
  local tmp
  tmp=$(mktemp "$(dirname "$1")/.jerboa.env.XXXXXX")
  chmod 600 "$tmp"
  {
    printf '# Jerboa backend secrets, created %s by deploy/deploy_app.sh.\n' "$(date -u +%FT%TZ)"
    printf '# Mode 0600. Never commit or paste this file. Read by docker --env-file:\n'
    printf '# KEY=VALUE per line; the value is taken literally (no quotes, no variable expansion).\n'
    printf 'db_pass=%s\n' "$2"
    printf 'flask_secret=%s\n' "$3"
  } > "$tmp"
  mv -f "$tmp" "$1"
}

# First run only: read db_pass the way the app itself sees it (pipenv loads the
# image's /chat_app/.env and python-dotenv strips the quotes), straight into a
# variable. It is never echoed.
# Runs inside $(...), i.e. in a subshell: clean up locally, not via cleanup_add.
read_legacy_db_pass() {
  local err rc=0
  err=$(mktemp)
  docker run --rm --network none --entrypoint "" "$BASE_IMAGE" \
    pipenv run python -c 'import os, sys; sys.stdout.write(os.environ.get("db_pass", ""))' 2>"$err" || rc=$?
  if (( rc != 0 )); then
    sed 's/^/  | /' "$err" >&2   # pipenv's own messages; they do not contain the value
  fi
  rm -f "$err"
  return "$rc"
}

ensure_env_file() {
  if [[ -f $ENV_FILE ]]; then
    check_secret_file_mode "$ENV_FILE"
    env_has db_pass "$ENV_FILE" || die "$ENV_FILE has no db_pass"
    env_has flask_secret "$ENV_FILE" || die "$ENV_FILE has no flask_secret"
    ok "$ENV_FILE exists (keys: $(grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$ENV_FILE" | tr -d '=' | tr '\n' ' '))"
    if [[ $ROTATE == 1 ]]; then
      local copy
      copy=$(backup_secret_file "$ENV_FILE" pre-rotate)
      env_set flask_secret "$(gen_secret)" "$ENV_FILE"
      ok "flask_secret rotated (previous file kept as $copy). Everyone signs in again."
    fi
    return 0
  fi
  if [[ -e $STATE_DIR/db.migrated ]]; then
    die "$ENV_FILE is missing, but the database was already migrated. Restore it from $STATE_DIR/jerboa.env.* rather than generating a new one."
  fi
  log "First run: taking db_pass from $BASE_IMAGE's .env (not printed) and generating a NEW flask_secret."
  local db_pass flask_secret
  db_pass=$(read_legacy_db_pass) || die "could not read db_pass from $BASE_IMAGE"
  [[ -n $db_pass ]] || die "db_pass is empty in $BASE_IMAGE's .env"
  [[ $db_pass != *$'\n'* ]] || die "db_pass contains a newline; it cannot go into an env file"
  flask_secret=$(gen_secret)
  write_env_file "$ENV_FILE" "$db_pass" "$flask_secret"
  unset db_pass flask_secret
  ok "created $ENV_FILE (0600) with db_pass (copied) and flask_secret (new)"
}

resolve_ref() { # <ref> -> full sha
  local r sha
  for r in "origin/$1" "refs/tags/$1" "$1"; do
    sha=$(git -C "$SRC_DIR" rev-parse --verify --quiet "$r^{commit}" 2>/dev/null || true)
    if [[ -n $sha ]]; then
      printf '%s' "$sha"
      return 0
    fi
  done
  return 1
}

show_status() {
  step "Backend containers"
  docker ps -a --filter label=jerboa.role=app --format '  {{.Names}}\t{{.Image}}\t{{.Status}}'
  local c
  for c in $(find_running_app_containers); do
    log "running: $c (image $(container_image "$c"), revision $(docker inspect -f '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$c" 2>/dev/null || true))"
  done
  log "state: current=$(state_get app.current) previous=$(state_get app.previous)"
  [[ -f $STATE_DIR/app.history ]] && { log "history (last 5):"; tail -n 5 "$STATE_DIR/app.history" | sed 's/^/    /'; }
  step "Health check"
  if app_health_check 10; then ok "healthy"; else warn "NOT healthy"; fi
}

do_rollback() {
  local cur prev
  prev=$(state_get app.previous)
  [[ -n $prev ]] || die "no previous container recorded in $STATE_DIR/app.previous"
  container_exists "$prev" || die "previous container $prev no longer exists"
  cur=$(find_running_app_containers | head -n1)
  step "Rollback: ${cur:-<nothing running>} -> $prev"
  if [[ -e $STATE_DIR/db.migrated ]] && ! container_env_names "$prev" | grep -qx db_user; then
    warn "$prev was created before the database migration and still points at the old"
    warn "database. Starting it will most likely fail its health check. To run older"
    warn "code against the new database, deploy that ref instead: ./deploy_app.sh <old-sha>"
  fi
  confirm "Stop ${cur:-nothing} and start $prev?" rollback || die "aborted; nothing changed"
  if [[ -n $cur ]]; then docker stop -t 20 "$cur" >/dev/null; ok "stopped $cur"; fi
  wait_port_free "$APP_PORT" || die "port $APP_PORT is still in use"
  docker start "$prev" >/dev/null
  if app_health_check 90; then
    state_set app.current "$prev"
    [[ -n $cur ]] && state_set app.previous "$cur"
    printf '%s rollback %s -> %s\n' "$(date -u +%FT%TZ)" "${cur:-none}" "$prev" >> "$STATE_DIR/app.history"
    ok "rolled back to $prev"
    set_rollback "./deploy_app.sh --rollback     # back to ${cur:-the previous one}"
    print_rollback
  else
    show_container_logs "$prev"
    if [[ -n $cur ]]; then
      warn "$prev is unhealthy; starting $cur again"
      docker stop -t 20 "$prev" >/dev/null || true
      wait_port_free "$APP_PORT" || true
      docker start "$cur" >/dev/null
      app_health_check 90 || warn "and $cur is not healthy either; investigate now (docker logs $cur)"
    fi
    die "rollback failed"
  fi
}

# ---------------------------------------------------------------- main ----

# The tests source this file with JERBOA_SOURCE_ONLY=1 to reach the helpers.
if [[ ${JERBOA_SOURCE_ONLY:-0} == 1 ]]; then return 0; fi

require_root
start_log
require_cmds docker git curl openssl python3 ss timeout

case $MODE in
  status) show_status; exit 0 ;;
  rollback) do_rollback; exit 0 ;;
esac

[[ -n $REF ]] || die "usage: ./deploy_app.sh <git-ref>   (see --help)"

step "Pre-flight"
mapfile -t apps < <(find_running_app_containers)
(( ${#apps[@]} <= 1 )) || die "more than one backend container is running: ${apps[*]}"
current=${apps[0]:-}
if [[ -n $current ]]; then
  ok "running backend: $current (image $(container_image "$current"))"
else
  warn "no backend container is running right now"
fi
docker image inspect "$BASE_IMAGE" >/dev/null 2>&1 || die "base image $BASE_IMAGE not found"
base_id=$(docker image inspect -f '{{.Id}}' "$BASE_IMAGE")
ok "base image $BASE_IMAGE = ${base_id#sha256:}"
mapfile -t pgs < <(find_running_pg_containers)
(( ${#pgs[@]} >= 1 )) || die "no Postgres container is running; the backend needs it"
ok "database container running: ${pgs[*]}"
require_disk_mb /var/lib/docker 1000 "image build and logs"
log "memory available: $(mem_available_mb) MB"

step "Fetching $REF into $SRC_DIR"
if [[ ! -d $SRC_DIR/.git ]]; then
  git clone --quiet --no-checkout "$REPO_URL" "$SRC_DIR"
fi
git -C "$SRC_DIR" remote set-url origin "$REPO_URL"
git -C "$SRC_DIR" fetch --quiet --prune --tags origin '+refs/heads/*:refs/remotes/origin/*'
sha=$(resolve_ref "$REF") || die "cannot resolve '$REF' (branch, tag or sha) in $REPO_URL"
short=${sha:0:12}
git -C "$SRC_DIR" -c advice.detachedHead=false checkout --quiet --force --detach "$sha"
git -C "$SRC_DIR" clean -fdxq
ok "checked out $short: $(git -C "$SRC_DIR" log -1 --format='%ad  %an  %s' --date=short)"
new=$APP_CONTAINER_PREFIX-$short
image=chat:$short

if [[ $new == "$current" && $FORCE == 0 ]]; then
  ok "$new is already running this commit; nothing to do (use --force to recreate it)"
  exit 0
fi

step "What changes compared to the running code"
work=$(mktemp -d)
cleanup_add "rm -rf '$work'"
copy_runpy=0
if [[ -n $current ]]; then
  docker cp "$current:/chat_app/app" "$work/running-app"
  docker cp "$current:/chat_app/run.py" "$work/running-run.py"
  docker cp "$current:/chat_app/Pipfile.lock" "$work/running-Pipfile.lock"
  docker exec "$current" ls /chat_app/migrations > "$work/running-migrations" 2>/dev/null || true
  diff_file="$STATE_DIR/deploy-$short.diff"
  mkdir -p "$STATE_DIR"
  diff -ruN --exclude=__pycache__ "$work/running-app" "$SRC_DIR/app" > "$diff_file" || true
  if [[ -s $diff_file ]]; then
    log "app/ changes (full diff: $diff_file):"
    diff -rqN --exclude=__pycache__ "$work/running-app" "$SRC_DIR/app" | sed "s#$work/running-app#running#; s#$SRC_DIR/app#new#" | sed 's/^/    /' || true
    log "    $(grep -c '^+[^+]' "$diff_file" || true) lines added, $(grep -c '^-[^-]' "$diff_file" || true) removed"
  else
    log "app/ is identical to the running code"
  fi
  if ! cmp -s "$work/running-run.py" "$SRC_DIR/run.py"; then
    copy_runpy=1
    warn "run.py differs from the running one; it will be copied too"
  fi
  if ! cmp -s "$work/running-Pipfile.lock" "$SRC_DIR/Pipfile.lock"; then
    warn "Pipfile.lock differs from the image. Dependency changes are NOT applied by"
    warn "this script: the new code runs on the 2020 dependency set. Make sure it does not need them."
  fi
  new_migrations=$(comm -13 <(sort "$work/running-migrations") \
      <(find "$SRC_DIR/migrations" -maxdepth 1 -name '*.py' -printf '%f\n' | sort) || true)
  if [[ -n $new_migrations ]]; then
    warn "this ref has database migrations the running image does not have:"
    indent <<<"$new_migrations"
    warn "they are NOT applied automatically (see RUNBOOK.md, 'Schema migrations')."
  fi
else
  copy_runpy=1
fi

# Two hand-made fixes live only in the running server.py; master lacks them.
if grep -q '^from werkzeug import secure_filename' "$SRC_DIR/app/server.py"; then
  warn "app/server.py does 'from werkzeug import secure_filename'. Werkzeug 1.0.1 in the"
  warn "image removed that; it needs 'from werkzeug.utils import secure_filename'. The smoke"
  warn "test below will fail on it."
fi
if ! grep -q 'ping_timeout' "$SRC_DIR/app/server.py"; then
  warn "app/server.py does not set SocketIO(ping_timeout=10, ping_interval=5), which the"
  warn "running server has. Clients will see the library defaults (60 s / 25 s) instead."
fi

step "Building $image"
ctx="$STATE_DIR/build/$short"
rm -rf "$ctx"
mkdir -p "$ctx"
cp -a "$SRC_DIR/app" "$ctx/app"
find "$ctx/app" -name __pycache__ -prune -exec rm -rf {} +
[[ $copy_runpy == 1 ]] && cp -a "$SRC_DIR/run.py" "$ctx/run.py"
render_dockerfile "$sha" "$base_id" "$copy_runpy" > "$ctx/Dockerfile"
sed 's/^/    /' "$ctx/Dockerfile"
docker build --network none -t "$image" "$ctx" | sed 's/^/  | /'
docker image inspect "$image" >/dev/null 2>&1 || die "build did not produce $image"
ok "built $image"

step "Secrets"
ensure_env_file

step "Smoke test: import the new code against the live database (nothing stopped yet)"
smoke="jerboa-smoke-$short"
docker rm -f "$smoke" >/dev/null 2>&1 || true
cleanup_add "docker rm -f '$smoke'"
if timeout 180 docker run --rm --name "$smoke" --network host --env-file "$ENV_FILE" \
     --entrypoint "" "$image" \
     pipenv run python -c 'import app.server as s; print("IMPORT_OK", s.app.import_name)' \
     > "$work/smoke.out" 2>&1 && grep -q IMPORT_OK "$work/smoke.out"; then
  ok "new code imports, finds its env vars and connects to the database"
else
  tail -n 30 "$work/smoke.out" | sed 's/^/  | /'
  die "smoke test failed; nothing was changed and ${current:-nothing} keeps serving"
fi

step "Plan"
cat <<EOF
  stop   ${current:-<nothing running>}   (kept, not removed: rollback target)
  start  $new   from $image
         --network host --restart unless-stopped --env-file $ENV_FILE
         -v $UPLOADS_DIR:/chat_app/data -v $EMOJIS_DIR:/chat_app/emojis
         log caps: json-file max-size=10m max-file=3
  API downtime: about 10-30 s. If flask_secret is new, everyone signs in again.
EOF
confirm "Switch the backend now?" deploy || die "aborted; nothing changed"

# A stopped container with the same name is an earlier deploy of this commit.
if container_exists "$new"; then
  if [[ $new == "$current" ]]; then
    replaced="$new-replaced-$(ts_utc)"
    docker rename "$current" "$replaced"
    current=$replaced
  else
    docker rm "$new" >/dev/null
  fi
fi

if [[ -n $current ]]; then
  set_rollback "./deploy_app.sh --rollback
# by hand:  docker stop $new; docker start $current"
  state_set app.previous "$current"
  docker stop -t 20 "$current" >/dev/null
  ok "stopped $current"
fi
wait_port_free "$APP_PORT" || die "port $APP_PORT is still in use after stopping $current"

run_app_container "$new" "$image" "$ENV_FILE"
ok "started $new"

if app_health_check 90 && verify_runtime_env "$new"; then
  state_set app.current "$new"
  printf '%s deploy %s (%s) %s -> %s\n' "$(date -u +%FT%TZ)" "$short" "$REF" "${current:-none}" "$new" >> "$STATE_DIR/app.history"
  step "Done: $new is serving"
  log "Watch the logs for a minute:  docker logs -f --tail 50 $new"
  log "Users must sign in again if flask_secret was (re)generated."
  print_rollback
  exit 0
fi

step "Health check FAILED: rolling back automatically"
set_rollback ""   # done right here, nothing left for the user to roll back
show_container_logs "$new" 60
docker stop -t 10 "$new" >/dev/null || true
docker rename "$new" "$new-failed-$(ts_utc)" || true
if [[ -n $current ]]; then
  wait_port_free "$APP_PORT" || true
  docker start "$current" >/dev/null
  if app_health_check 90; then
    state_set app.current "$current"
    ok "$current is serving again"
  else
    warn "$current is not healthy either. Look at: docker logs --tail 100 $current"
  fi
fi
die "deploy of $short failed; the failed container is kept as $new-failed-* for debugging"
